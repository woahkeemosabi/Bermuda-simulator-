import './headless.mjs';
import assert from 'node:assert/strict';
import {GPU} from '../src/engine/gpu/GPU.js';
import {RenderTarget} from '../src/engine/gpu/Texture.js';
import {readTexture} from '../src/engine/gpu/Readback.js';
import {MeshRenderer} from '../src/engine/render/MeshRenderer.js';
import {SunShadows} from '../src/engine/render/Shadows.js';
import {Material} from '../src/engine/render/Material.js';
import {setFrameCamera} from '../src/engine/render/Frame.js';
import * as E from '../src/engine/index.js';
await GPU.init({headless:true});
new SunShadows();
const errors=[];GPU.device.addEventListener('uncapturederror',e=>errors.push(e.error.message));
const scene=new E.Scene(),geo=new E.PlaneGeometry(1.5,1.5);
const red=new Material({name:'red',lit:false,color:0xff0000}),blue=new Material({name:'blue',lit:false,color:0x0000ff});
const a=new E.Mesh(geo,red),b=new E.Mesh(geo,blue);a.position.x=-1;b.position.x=1;scene.add(a,b);
const camera=new E.PerspectiveCamera(45,2,.1,100);camera.position.z=5;camera.lookAt(0,0,0);
const mr=new MeshRenderer(),rt=new RenderTarget(256,128,{colors:['rgba8unorm'],depth:'depth32float'});
const pass={camera,kind:'color',colorViews:[rt.texture.view()],colorFormats:rt.formats,depthView:rt.depthTexture.view(),depthFormat:'depth32float',clearDepth:0,clearColors:[[0,0,0,1]]};
mr.precompiling=true;mr.render(scene,pass);await GPU.pipelinesReady();mr.precompiling=false;
GPU.beginFrame();setFrameCamera(camera,256,128);mr.render(scene,pass);GPU.submit();await GPU.whenIdle();
const r=await readTexture(rt.texture),p=new Uint8Array(r.data),sample=x=>[...p.slice((64*256+x)*4,(64*256+x)*4+3)];
const left=sample(97),right=sample(159);
assert.ok(left[0]>200&&left[2]<10,JSON.stringify(left));assert.ok(right[2]>200&&right[0]<10,JSON.stringify(right));
assert.deepEqual(errors,[]);
const handles=new Set([...mr.pipelines.values()].map(p=>p.handle));
if(process.env.EXPECT_SHARED==='1')assert.equal(handles.size,1);
console.log(JSON.stringify({materialInstances:2,materialBindingSets:mr.pipelines.size,nativePrograms:handles.size,left,right,errors}));
process.exit(0);
